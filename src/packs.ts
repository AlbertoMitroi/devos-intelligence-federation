// System context packs (PLAN pipeline 6): deterministic Markdown for AI agents. Every statement cites evidence as
// `{input}:{path}:{line}`; every card ends with what could not be determined. No generated prose beyond templates.
import { compareOrdinal } from './util/canonical.ts';
import type { Federation } from './federate.ts';
import type { Rec } from './records.ts';

export type Where = (evidenceId: string) => string | null;

const MAX_ROWS = 60;

function slug(s: string): string {
  return s.replace(/[^A-Za-z0-9._-]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 80) || 'item';
}

function shortEntity(id: unknown): string {
  if (typeof id !== 'string') return '(unknown)';
  const [input, rest] = [id.slice(0, id.indexOf('/')), id.slice(id.indexOf('/') + 1)];
  const dotnet = /^dotnet:(?:pkg:[^:]+:)?[^:]+:[A-Z]:(.+)$/.exec(rest);
  if (dotnet) return `${input}: ${dotnet[1].replace(/\(.*\)$/, '()')}`;
  const ts = /^ts:[^:]+:(.+)$/.exec(rest);
  if (ts) return `${input}: ${ts[1]}`;
  return `${input}: ${rest}`;
}

function cite(where: Where, evidence: unknown, max = 3): string {
  const list = ((evidence as string[] | undefined) ?? []).map(where).filter((w): w is string => !!w);
  const uniq = [...new Set(list)].sort(compareOrdinal);
  if (!uniq.length) return '';
  const shown = uniq.slice(0, max).map((w) => `\`${w}\``).join(', ');
  return uniq.length > max ? `${shown} (+${uniq.length - max})` : shown;
}

function endpointLabel(l: Rec, side: 'from' | 'to'): string {
  const e = l[side] as Rec | null;
  if (!e) return '(none)';
  return shortEntity(e.entity ?? e.observation);
}

function linkLine(l: Rec, where: Where): string {
  const m = (l.match ?? {}) as Rec;
  let what = '';
  if (l.via === 'http') what = `${m.method ?? '?'} ${m.route ?? '?'}${m.endpointRoute && m.endpointRoute !== m.route ? ` (endpoint ${m.endpointRoute})` : ''}`;
  else if (l.via === 'messaging') what = `${m.contract ?? '?'} on ${((m.destination as Rec | undefined)?.names as string[] | undefined)?.join(' / ') || 'unknown destination'}`;
  else if (l.via === 'realtime') what = `method ${m.method ?? '?'}`;
  const through = (l.from as Rec).through as Rec | undefined;
  const pkg = through ? ` through package ${(through.package as Rec).id}@${(through.package as Rec).version} (version match ${through.versionMatch})` : '';
  const reason = l.reason ? ` Reason: ${l.reason}.` : '';
  return `- **${l.resolution}** ${endpointLabel(l, 'from')} → ${l.to ? endpointLabel(l, 'to') : 'no target'}: ${what}${pkg}. Evidence: ${cite(where, l.evidence)}.${reason}`;
}

function table(header: string[], rows: string[][]): string {
  const esc = (c: string) => c.replace(/\|/g, '\\|').replace(/\n/g, ' ');
  return [`| ${header.join(' | ')} |`, `|${header.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.map(esc).join(' | ')} |`)].join('\n');
}

function capped<T>(list: T[], render: (t: T) => string, what: string): string[] {
  const out = list.slice(0, MAX_ROWS).map(render);
  if (list.length > MAX_ROWS) out.push(`- ${list.length - MAX_ROWS} more ${what} omitted; query \`graph/links.ndjson\` or the \`links\` table of \`index.sqlite\`.`);
  return out;
}

export function buildPacks(fed: Federation, inputsRecords: Rec[], where: Where): Map<string, string> {
  const files = new Map<string, string>();
  const cross = fed.links;
  const byResolution = (list: Rec[]) => ['exact', 'ambiguous', 'candidate', 'unresolved'].map((r) => `${r} ${list.filter((l) => l.resolution === r).length}`).join(', ');
  const excluded = fed.states.filter((s) => !s.input);

  // overview
  const ov: string[] = [];
  ov.push(`# System ${fed.config.system}`, '');
  ov.push(`Generated by intelligence-federation from ${fed.states.length} input generations. Every link below names its evidence as \`input:path:line\`.`, '');
  ov.push('## Inputs', '');
  ov.push(table(['Input', 'Repository', 'Commit', 'Engine', 'Status', 'Verification'], inputsRecords.map((i) => [String(i.id), String((i.repository as Rec | null)?.remoteUrl ?? 'unknown'), String(i.commit ?? 'unknown').slice(0, 12), i.engine ? `${(i.engine as Rec).name}@${(i.engine as Rec).version}` : 'unknown', String(i.status ?? 'unknown'), String((i.verification as Rec).result)])));
  ov.push('', '## Cross-repository links', '');
  for (const via of ['http', 'messaging', 'realtime']) {
    const list = cross.filter((l) => l.via === via);
    ov.push(`- ${via}: ${list.length} (${byResolution(list)})`);
  }
  ov.push(`- package (implemented_by_package): ${fed.packageLinks.length} (${byResolution(fed.packageLinks)})`);
  ov.push(`- traces across two or more links: ${fed.traces.length}`, '');
  ov.push('See [service-map.md](service-map.md), one card per repository in `repositories/`, one per message contract in `contracts/`, and [traces.md](traces.md).', '');
  ov.push('## Packages produced inside the system', '');
  ov.push(
    fed.packages.length
      ? table(['Package', 'Consumed', 'Consumer', 'Producer', 'Produced', 'Version match', 'Resolution'], fed.packages.map((p) => [String(p.packageId), String(p.version), `${(p.consumer as Rec).input} (${((p.consumer as Rec).projects as string[]).join(', ') || 'no project lists it'})`, `${(p.producer as Rec).input}:${(p.producer as Rec).project}`, String((p.producer as Rec).packageVersion ?? 'unknown'), String(p.versionMatch), String(p.resolution)]))
      : 'None.',
  );
  ov.push('', '## Unresolved', '');
  const unresolved = cross.filter((l) => l.resolution === 'unresolved');
  ov.push(...(unresolved.length ? capped(unresolved, (l) => linkLine(l, where), 'unresolved links') : ['None.']));
  ov.push('', '## What could not be determined', '');
  const gaps: string[] = [];
  for (const s of excluded) gaps.push(`- Input ${s.name} was excluded: ${s.verification.errors.slice(0, 3).join('; ')}.`);
  for (const n of fed.notes) gaps.push(`- ${n.message}`);
  for (const p of fed.packages) if (p.reason) gaps.push(`- ${p.packageId}@${p.version}: ${p.reason}.`);
  ov.push(...(gaps.length ? gaps : ['- Nothing was reported.']), '');
  files.set('context/overview.md', ov.join('\n'));

  // service map
  const edges = new Map<string, Map<string, number>>();
  const count = (from: string, to: string, label: string) => {
    const key = `${from}\u0000${to}`;
    const m = edges.get(key) ?? new Map<string, number>();
    m.set(label, (m.get(label) ?? 0) + 1);
    edges.set(key, m);
  };
  for (const l of cross) if (l.to) count((l.from as Rec).input as string, (l.to as Rec).input as string, `${l.via}`);
  for (const p of fed.packages) count((p.consumer as Rec).input as string, (p.producer as Rec).input as string, 'package');
  const sm: string[] = ['# Service map', '', 'Edges are cross-repository links (count per kind); `package` means the consumer uses a package whose source is in the producer.', '', '```mermaid', 'flowchart LR'];
  for (const s of [...fed.states].sort((a, b) => compareOrdinal(a.name, b.name))) sm.push(`  ${s.name.replace(/-/g, '_')}["${s.name}${s.input ? '' : ' (excluded)'}"]`);
  for (const [key, labels] of [...edges].sort(([a], [b]) => compareOrdinal(a, b))) {
    const [from, to] = key.split('\u0000');
    const label = [...labels].sort(([a], [b]) => compareOrdinal(a, b)).map(([k, n]) => `${k} ${n}`).join(', ');
    sm.push(`  ${from.replace(/-/g, '_')} -->|${label}| ${to.replace(/-/g, '_')}`);
  }
  sm.push('```', '', 'Resolution legend: exact (one target, every part known), ambiguous (several targets), candidate (a part is inferred, the reason says which), unresolved (no target, with the reason).', '');
  files.set('context/service-map.md', sm.join('\n'));

  // repository cards
  for (const s of [...fed.states].sort((a, b) => compareOrdinal(a.name, b.name))) {
    const name = s.name;
    const rec = inputsRecords.find((i) => i.id === name)!;
    const out = cross.filter((l) => (l.from as Rec).input === name);
    const inbound = cross.filter((l) => l.to && (l.to as Rec).input === name);
    const c: string[] = [`# Repository ${name}`, ''];
    c.push(`- Repository: ${String((rec.repository as Rec | null)?.remoteUrl ?? 'unknown')}`, `- Commit: ${String(rec.commit ?? 'unknown')}`, `- Engine: ${rec.engine ? `${(rec.engine as Rec).name}@${(rec.engine as Rec).version}` : 'unknown'}`, `- Verification: ${(rec.verification as Rec).result}`, '');
    c.push('## Outgoing links', '', ...(out.length ? capped(out, (l) => linkLine(l, where), 'outgoing links') : ['None.']), '');
    c.push('## Incoming links', '', ...(inbound.length ? capped(inbound, (l) => linkLine(l, where), 'incoming links') : ['None.']), '');
    const consumed = fed.packages.filter((p) => (p.consumer as Rec).input === name);
    const produced = fed.packages.filter((p) => (p.producer as Rec).input === name);
    c.push('## Packages', '');
    for (const p of consumed) c.push(`- Consumes ${p.packageId}@${p.version} from ${(p.producer as Rec).input}:${(p.producer as Rec).project} (version match ${p.versionMatch}, ${p.resolution}; ${(p.entities as Rec).resolved}/${(p.entities as Rec).used} symbols resolved).`);
    for (const p of produced) c.push(`- Produces ${p.packageId} (from ${(p.producer as Rec).project}), consumed by ${(p.consumer as Rec).input} at ${p.version} (version match ${p.versionMatch}).`);
    if (!consumed.length && !produced.length) c.push('None inside the system.');
    c.push('', '## What could not be determined', '');
    const g: string[] = [];
    if (!s.input) g.push(`- The input was excluded: ${s.verification.errors.slice(0, 3).join('; ')}.`);
    for (const r of s.verification.references.slice(0, 5)) g.push(`- Input defect (dangling reference, kept): ${r}.`);
    for (const n of fed.notes.filter((x) => x.scope === name)) g.push(`- ${n.message}`);
    for (const l of out.filter((x) => x.resolution !== 'exact' && x.reason)) g.push(`- ${endpointLabel(l, 'from')}: ${l.reason}.`);
    c.push(...(g.length ? [...new Set(g)].slice(0, MAX_ROWS) : ['- Nothing was reported.']), '');
    files.set(`context/repositories/${slug(name)}.md`, c.join('\n'));
  }

  // contract cards: messages and real-time methods that cross repositories (or leave the system)
  const contracts = new Map<string, Rec[]>();
  for (const l of cross) {
    const m = (l.match ?? {}) as Rec;
    let key: string | null = null;
    if (l.via === 'messaging') key = `message-${m.contract ?? 'unknown'}`;
    else if (l.via === 'realtime') key = `realtime-${m.method ?? 'unknown'}`;
    if (!key) continue;
    const list = contracts.get(key) ?? [];
    list.push(l);
    contracts.set(key, list);
  }
  for (const [key, list] of [...contracts].sort(([a], [b]) => compareOrdinal(a, b))) {
    const c: string[] = [`# ${key.startsWith('message-') ? 'Message' : 'Real-time method'} ${key.slice(key.indexOf('-') + 1)}`, ''];
    c.push('## Links', '', ...capped(list, (l) => linkLine(l, where), 'links'), '');
    c.push('## What could not be determined', '');
    const g = [...new Set(list.filter((l) => l.reason).map((l) => `- ${l.reason}.`))];
    c.push(...(g.length ? g : ['- Nothing was reported.']), '');
    files.set(`context/contracts/${slug(key)}.md`, c.join('\n'));
  }

  // traces
  const tr: string[] = ['# Traces', '', `Chains of two or more cross-repository links joined by bounded call paths inside a repository (at most 8 steps). ${fed.traces.length} traces.`, ''];
  for (const t of fed.traces.slice(0, MAX_ROWS)) {
    tr.push(`## ${shortEntity(t.start)} → ${shortEntity(t.end)}`, '', `Resolution **${t.resolution}** (weakest segment ${(t.weakest as Rec).segment}).`, '');
    (t.segments as Rec[]).forEach((s, i) => {
      if (s.type === 'link') tr.push(`${i}. link ${s.kind} (${s.via}) ${shortEntity(s.from)} → ${shortEntity(s.to)}, ${s.resolution}. Evidence: ${cite(where, s.evidence, 2)}.`);
      else tr.push(`${i}. inside ${s.input}: ${s.kind} → ${shortEntity(s.to)}, ${s.resolution}${(s.evidence as string[]).length ? `. Evidence: ${cite(where, s.evidence, 1)}` : ''}.`);
    });
    tr.push('');
  }
  if (fed.traces.length > MAX_ROWS) tr.push(`${fed.traces.length - MAX_ROWS} more traces omitted; see \`graph/traces.ndjson\`.`, '');
  tr.push('## What could not be determined', '', '- Paths through reflection, conventions or configuration that no input records as a relation or link are not followed; a trace stops there.', '');
  files.set('context/traces.md', tr.join('\n'));
  return files;
}
